//! JSON-lines log at `${CLAUDE_PLUGIN_DATA}/log/tap.log` (mode 0600).
//!
//! Only fixed vocabulary reaches the log: the event name (from a fixed list),
//! a short session id (validated charset), our own episode id, a transition,
//! a category, and an error *kind*. Never message text, never serde errors.

use std::io::Write;
use std::os::unix::fs::OpenOptionsExt;

use serde::Serialize;

use crate::contract::Category;

/// Truncate the log when it grows past this size.
pub const LOG_MAX_BYTES: u64 = 1 << 20;

#[derive(Debug, Default, Serialize)]
pub struct Entry {
    pub ts: i64,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub event: Option<&'static str>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub session: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub episode: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub transition: Option<&'static str>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub category: Option<&'static str>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub kind: Option<&'static str>,
}

impl Entry {
    pub fn new(event: &'static str) -> Self {
        Entry {
            ts: crate::state::now(),
            event: Some(event),
            ..Default::default()
        }
    }

    /// Only the first 8 characters of an already validated session id.
    pub fn session(mut self, id: &str) -> Self {
        if crate::state::valid_session_id(id) {
            self.session = Some(id.chars().take(8).collect());
        }
        self
    }

    pub fn episode(mut self, id: &str) -> Self {
        // Episode ids are generated by us (hex), but filter anyway.
        if id.len() <= 32 && id.chars().all(|c| c.is_ascii_hexdigit()) {
            self.episode = Some(id.to_string());
        }
        self
    }

    pub fn transition(mut self, t: &'static str) -> Self {
        self.transition = Some(t);
        self
    }

    pub fn category(mut self, c: Category) -> Self {
        self.category = Some(c.as_str());
        self
    }

    pub fn kind(mut self, k: &'static str) -> Self {
        self.kind = Some(k);
        self
    }

    /// Append to the log. Failures are silently ignored: logging must never
    /// change hook behaviour.
    pub fn write(self) {
        let _ = write_entry(&self);
    }
}

fn write_entry(e: &Entry) -> std::io::Result<()> {
    let Some(data) = crate::state::data_dir() else {
        return Ok(());
    };
    let dir = crate::state::private_subdir(&data, "log")?;
    let path = dir.join("tap.log");
    let mut f = std::fs::OpenOptions::new()
        .append(true)
        .create(true)
        .mode(0o600)
        .custom_flags(libc::O_NOFOLLOW)
        .open(&path)?;
    if f.metadata()?.len() > LOG_MAX_BYTES {
        f.set_len(0)?;
    }
    let mut line = serde_json::to_vec(e).map_err(std::io::Error::other)?;
    line.push(b'\n');
    f.write_all(&line)
}
